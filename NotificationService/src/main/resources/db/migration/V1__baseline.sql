-- -----------------------------------------------------------------------------
-- notification_log  -  the only table in this service
--
-- THE MOST IMPORTANT LINE IN THIS FILE is the UNIQUE KEY on
-- (event_id, recipient_email). It is not just a tidiness constraint - it is this
-- service's entire protection against sending the same person the same email twice.
--
-- Why that protection is needed: Kafka guarantees "at least once" delivery, so the
-- same event CAN legitimately arrive twice (after a retry, a rebalance, or a
-- restart). Without the unique key, a duplicate delivery means a duplicate email.
--
-- How it is used: the service does not check-then-insert (two users could both
-- pass the check at the same moment and both insert). Instead it just inserts and
-- lets the database reject the duplicate - see the DataIntegrityViolationException
-- catch in EmailNoticationService. The database is the referee, so it works
-- correctly even with several consumers running at once.
--
-- NOTE: despite the name, this service does not currently send email at all - the
-- send step is an empty try block. This table is a log of emails that WOULD have
-- been sent. See CLAUDE.md section 9 item 16.
-- -----------------------------------------------------------------------------
CREATE TABLE `notification_log` (
  `id`              binary(16)   NOT NULL,

  `event_id`        binary(16)   NOT NULL,   -- the Kafka event that triggered this
  `event_type`      enum('INCIDENT_ASSIGNED','INCIDENT_CREATED','INCIDENT_METADATA_UPDATED','INCIDENT_REOPENED','INCIDENT_RESOLVED','INCIDENT_STATUS_UPDATED','USER_REGISTERED','USER_UPDATED') DEFAULT NULL,
  `incident_id`     binary(16)   DEFAULT NULL,
  `performed_by`    binary(16)   DEFAULT NULL,  -- who did the thing being notified about

  `recipient_email` varchar(255) DEFAULT NULL,
  `recipient_name`  varchar(255) DEFAULT NULL,

  `status`          enum('FAILED','PENDING','SUCCESS') DEFAULT NULL,
  `message`         varchar(255) DEFAULT NULL,
  `failure_reason`  varchar(255) DEFAULT NULL,

  `created_at`      datetime(6)  DEFAULT NULL,
  `sent_at`         datetime(6)  DEFAULT NULL,

  PRIMARY KEY (`id`),

  -- The duplicate-email guard described above.
  UNIQUE KEY `UKb1yttpudyk8bdq4a584abwe5n` (`event_id`,`recipient_email`),

  -- Generated by Hibernate, not written by hand. Reproduced exactly as it exists
  -- in the real database, because that is this file's job.
  -- Worth a closer look later: see the note at the bottom of this file.
  CONSTRAINT `notification_log_chk_1` CHECK ((`event_type` between 0 and 7))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;


-- =============================================================================
-- SOMETHING TO INVESTIGATE (not a change - just do not let it get forgotten)
--
-- That CHECK constraint says `event_type between 0 and 7`.
--
-- In MySQL, comparing an ENUM column against numbers uses the value's POSITION,
-- and positions start at 1 (0 is reserved for the invalid/empty value). This
-- column has 8 possible values, so their positions are 1 through 8.
--
-- Which means the 8th value - USER_UPDATED, last in the list - sits at position 8
-- and may fall outside "between 0 and 7".
--
-- It has likely never been hit, because this service only consumes incident
-- events, so USER_UPDATED is probably never written. That is exactly why it is
-- worth writing down now rather than discovering it later.
--
